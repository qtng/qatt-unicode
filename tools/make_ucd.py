"""Generate the draft Unicode Character Database files in ../ucd from qatt_grammar.

Usage: python tools/make_ucd.py

Code points use the provisional BLOCK_BASE of qatt_grammar; only the offsets in
the block come from the proposal. Values that the proposal marks [TBD] are
filled with the most likely value and listed in ucd/questions.md.
"""

from __future__ import annotations

from pathlib import Path
import unicodedata

import qatt_grammar as q

OUT = Path(__file__).resolve().parent.parent / "ucd"

NOM_ANNOTATIONS = ("翁", "⿰木禺", "胸", "⿰木功", "工", "⿰竜羽", "⿰竜里", "東", "農", "宗", "通",
                   "⿰亻戍", "柊", "⿰月容", "衝", "空", "滝", "⿱山庸", "蒙", "芃", "⿰木芃", "⿰口風")
READINGS = ("ông", "ngông", "hông", "gông", "công", "lông", "trông", "đông", "nông", "tông", "thông",
            "nhông", "chông", "dông", "xông", "không", "sông", "rông", "mông", "bông", "vông", "phông")

BLOCK_NAME = "Quoc Am Tan Tu"
SCRIPT = "Quoc_Am_Tan_Tu"

# Per kind: General_Category, Canonical_Combining_Class, Bidi_Class,
# Grapheme_Cluster_Break, Indic_Conjunct_Break, Line_Break,
# East_Asian_Width, Vertical_Orientation
PROPS = {
    q.Kind.CAN_TU:   ("Lo", 0, "L",   "Other",  "Consonant", "ID", "W", "U"),
    q.Kind.UNMARKED: ("Lo", 0, "L",   "Other",  "Consonant", "ID", "W", "U"),
    q.Kind.CHI_TU:   ("Lo", 0, "L",   "Other",  "Consonant", "ID", "W", "U"),
    q.Kind.COMBINER: ("Cf", 0, "BN",  "Extend", "Linker",    "GL", "N", "U"),
    q.Kind.JOINER:   ("Cf", 0, "BN",  "Extend", "Linker",    "GL", "N", "U"),
    q.Kind.TONE:     ("Mn", 0, "NSM", "Extend", "Extend",    "CM", "N", "U"),
}

HEADER = """# {name}
# DRAFT for the Quốc Âm Tân Tự proposal - not part of the Unicode Standard.
# Generated by tools/make_ucd.py; do not edit by hand.
# Code points are provisional: block base U+{base:05X} stands in for the
# position the UTC will assign; only the offsets come from the proposal.
"""


def assigned():
    for offset in range(q.BLOCK_SIZE):
        ch = chr(q.BLOCK_BASE + offset)
        if q.kind(ch) is not q.Kind.OTHER:
            yield ch


def write(name: str, lines: list[str]) -> None:
    text = HEADER.format(name=name, base=q.BLOCK_BASE) + "\n" + "\n".join(lines) + "\n"
    (OUT / name).write_text(text, encoding="utf-8")


def unicode_data() -> list[str]:
    lines = []
    for ch in assigned():
        gc, ccc, bidi = PROPS[q.kind(ch)][:3]
        lines.append(f"{ord(ch):05X};{q.character_name(ch)};{gc};{ccc};{bidi};;;;;N;;;;;")
    return [l for l in lines]


def property_file(index: int, prop: str) -> list[str]:
    """Ranges of equal value for one property, in the style of the UCD property files."""
    lines, run = [], []
    def flush():
        if run:
            first, last, value = run[0], run[-1], PROPS[q.kind(run[0])][index]
            span = f"{ord(first):05X}" if first == last else f"{ord(first):05X}..{ord(last):05X}"
            names = q.character_name(first) + ("" if first == last else ".." + q.character_name(last))
            lines.append(f"{span:<13}; {value:<9} # {names}")
    for ch in assigned():
        if run and PROPS[q.kind(ch)][index] != PROPS[q.kind(run[-1])][index]:
            flush(); run = []
        run.append(ch)
    flush()
    return [f"# Property: {prop}", ""] + lines


def names_list() -> list[str]:
    first, last = q.BLOCK_BASE, q.BLOCK_BASE + q.BLOCK_SIZE - 1
    lines = [f"@@\t{first:05X}\t{BLOCK_NAME}\t{last:05X}"]
    headings = {q.Kind.UNMARKED: "Forms without marking stroke",
                q.Kind.CAN_TU: "Forms with marking stroke (the six positions of each base)",
                q.Kind.COMBINER: "Format characters",
                q.Kind.TONE: "Tone marks"}
    shown = None
    for ch in assigned():
        k = q.kind(ch)
        group = q.Kind.CAN_TU if k is q.Kind.CHI_TU else k
        if group is not shown and group in headings:
            lines.append(f"@\t\t{headings[group]}")
        shown = group
        lines.append(f"{ord(ch):05X}\t{q.character_name(ch)}")
        base = q.base_of(ch)
        if k is q.Kind.UNMARKED:
            lines.append(f"\t* no marking stroke; standalone, it has the reading of the Cán Tự of its base: {READINGS[base]} {NOM_ANNOTATIONS[base]}")
        elif k is q.Kind.CAN_TU:
            lines.append(f"\t* Cán Tự of the source listing: {READINGS[base]} {NOM_ANNOTATIONS[base]}")
        elif k is q.Kind.CHI_TU:
            lines.append(f"\t* Chi Tự of the base {READINGS[base]}")
        elif k is q.Kind.COMBINER:
            lines.append("\t* places the following Chi Tự above a Hợp Thư")
        elif k is q.Kind.JOINER:
            lines.append("\t* joins two components into one character; their order gives the arrangement")
        elif k is q.Kind.TONE:
            index = ord(ch) - q.BLOCK_BASE - q.TONE_OFFSET
            corner = q.TONE_CORNERS[index // len(q.TONE_SHAPES)]
            shape = q.TONE_SHAPES[index % len(q.TONE_SHAPES)]
            lines.append(f"\t= {q.TONE_NAMES[(shape, corner)]}")
            modifier = chr(0xA700 + index)       # same tone, spacing modifier letter
            ideographic = chr(0x302A + q.TONE_CORNERS.index(corner))  # same corner, no register
            for related in (modifier, ideographic):
                lines.append(f"\tx ({unicodedata.name(related).lower()} - {ord(related):04X})")
    return lines


def main() -> None:
    OUT.mkdir(exist_ok=True)
    write("UnicodeData-draft.txt", unicode_data())
    sections = []
    for index, prop in ((3, "Grapheme_Cluster_Break"), (4, "Indic_Conjunct_Break"), (5, "Line_Break"),
                        (6, "East_Asian_Width"), (7, "Vertical_Orientation")):
        sections += property_file(index, prop) + [""]
    first, last = q.BLOCK_BASE, q.BLOCK_BASE + q.BLOCK_SIZE - 1
    sections += ["# Property: Script", "",
                 f"{first:05X}..{q.BLOCK_BASE + q.RESERVED_OFFSET - 1:05X} ; {SCRIPT}", "",
                 "# Property: Block", "", f"{first:05X}..{last:05X} ; {BLOCK_NAME}"]
    write("Properties-draft.txt", sections)
    write("NamesList-draft.txt", names_list())


if __name__ == "__main__":
    main()
